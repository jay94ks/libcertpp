/*
 * PKCS#10 (RFC 2986) certification-request tests.
 *
 * Nothing here relies solely on "this library built it, this library parsed it" -- a builder and
 * a parser that share one mistake agree with each other perfectly, which is how most of the bugs
 * in docs/changelog.md got in. So the acceptance fixtures below are all externally produced:
 *
 *  - OSSL_* are real `openssl req` output (OpenSSL 3.4.0), one per signature family, including
 *    one with no attributes at all and one with a PKCS#9 extensionRequest.
 *  - HAND_MULTI_ATTR_CSR was assembled byte by byte from RFC 2986's own ASN.1 (a short Python
 *    script, no ASN.1 library), signed with `openssl dgst -sign`, and then confirmed by
 *    `openssl req -verify` -- so its two-attribute SET, its DER SET-OF ordering and its
 *    challengePassword are all encodings this library's own encoder never produced.
 *  - HAND_NO_ATTRS_CSR is the same, with the `attributes [0]` field deliberately left out: the
 *    negative control for RFC 2986 4.1's "attributes is not OPTIONAL". OpenSSL itself accepts
 *    this one, so it is not a strawman.
 */

